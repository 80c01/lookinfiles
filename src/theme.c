/* Application-wide CSS theme (VS Code Dark Modern inspired panels, toolbars,
 * tabs). Colours are the palette roles (palette.h) as CSS named colours,
 * fonts and sizes the font roles (fonts.h: @font_ui, @size_normal...). */
#include "theme.h"
#include "palette.h"
#include "fonts.h"
#include "theme_store.h"
#include "file_type_icons.h"

#include <gtk/gtk.h>

/* Every stylesheet added with theme_add_css(), kept to be reloaded with
 * the palette's current values by theme_reload() */
typedef struct {
    GtkCssProvider* provider;
    const gchar* source;
} ThemeSheet;

static GPtrArray* sheets = NULL;

static void sheet_load(ThemeSheet* sheet) {
    gchar* defines = palette_css_defines();
    gchar* source = fonts_expand(sheet->source);
    gchar* css = g_strconcat(defines, source, NULL);
    g_free(source);
    gtk_css_provider_load_from_string(sheet->provider, css);
    g_free(css);
    g_free(defines);
}

void theme_add_css(const gchar* css) {
    GdkDisplay* display = gdk_display_get_default();
    if (display == NULL || css == NULL) {
        return;
    }
    if (sheets == NULL) {
        sheets = g_ptr_array_new_with_free_func(g_free);
    }
    ThemeSheet* sheet = g_new0(ThemeSheet, 1);
    sheet->provider = gtk_css_provider_new();
    sheet->source = css;
    sheet_load(sheet);
    gtk_style_context_add_provider_for_display(display, GTK_STYLE_PROVIDER(sheet->provider),
                                               GTK_STYLE_PROVIDER_PRIORITY_APPLICATION);
    g_ptr_array_add(sheets, sheet);
}

void theme_reload(void) {
    for (guint i = 0; sheets != NULL && i < sheets->len; i++) {
        sheet_load(g_ptr_array_index(sheets, i));
    }
}

gboolean theme_apply_saved(void) {
    gchar* dir = theme_store_user_dir();
    gchar* choice_path = theme_store_choice_path();
    GPtrArray* errors = g_ptr_array_new_with_free_func(g_free);
    GPtrArray* themes = theme_store_list(dir, errors);
    for (guint i = 0; i < errors->len; i++) {
        g_printerr("[ Theme skipped: %s ]\n", (const gchar*)g_ptr_array_index(errors, i));
    }
    gchar* name = theme_store_load_choice(choice_path);
    gboolean dark = TRUE;
    GError* error = NULL;
    if (!theme_store_apply(themes, name, &dark, &error)) {
        g_printerr("[ Theme \"%s\" not applied: %s ]\n", name, error->message);
        g_clear_error(&error);
        theme_store_apply(themes, THEME_DEFAULT_NAME, &dark, NULL);
    }
    /* The user's fonts over the theme's; zoom measured from the theme */
    fonts_mark_base();
    FontChoice fonts = {0};
    theme_store_load_fonts(choice_path, &fonts);
    theme_store_apply_fonts(&fonts);
    font_choice_clear(&fonts);
    g_free(name);
    g_ptr_array_free(themes, TRUE);
    g_ptr_array_free(errors, TRUE);
    g_free(choice_path);
    g_free(dir);
    return dark;
}

