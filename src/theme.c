/* Application-wide CSS theme (VS Code Dark Modern inspired panels, toolbars,
 * tabs). Colours are the palette roles (palette.h) as CSS named colours. */
#include "theme.h"
#include "palette.h"

#include <gtk/gtk.h>

/* Every stylesheet added with theme_add_css(), kept to be reloaded with
 * the palette's current values by theme_reload() */
typedef struct {
    GtkCssProvider* provider;
    const gchar* source;
} ThemeSheet;

static GPtrArray* sheets = NULL;

static void sheet_load(ThemeSheet* sheet) {
    gchar* defines = palette_css_defines();
    gchar* css = g_strconcat(defines, sheet->source, NULL);
    gtk_css_provider_load_from_string(sheet->provider, css);
    g_free(css);
    g_free(defines);
}

void theme_add_css(const gchar* css) {
    GdkDisplay* display = gdk_display_get_default();
    if (display == NULL || css == NULL) {
        return;
    }
    if (sheets == NULL) {
        sheets = g_ptr_array_new_with_free_func(g_free);
    }
    ThemeSheet* sheet = g_new0(ThemeSheet, 1);
    sheet->provider = gtk_css_provider_new();
    sheet->source = css;
    sheet_load(sheet);
    gtk_style_context_add_provider_for_display(display, GTK_STYLE_PROVIDER(sheet->provider),
                                               GTK_STYLE_PROVIDER_PRIORITY_APPLICATION);
    g_ptr_array_add(sheets, sheet);
}

void theme_reload(void) {
    for (guint i = 0; sheets != NULL && i < sheets->len; i++) {
        sheet_load(g_ptr_array_index(sheets, i));
    }
}

